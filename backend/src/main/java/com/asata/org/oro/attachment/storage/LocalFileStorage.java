package com.asata.org.oro.attachment.storage;

import com.asata.org.oro.exception.ServiceUnavailable;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Component;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.security.DigestInputStream;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.regex.Pattern;

/**
 * The files on a local disk (oro.attachments.local-dir), for development and single-server installs: a deployment uses
 * an object storage instead. A file is written to a temporary name, then moved under its key once complete, so a
 * partial upload is never served.
 */
@Slf4j
@Component
@ConditionalOnProperty(prefix = "oro.attachments", name = "storage-provider", havingValue = "local")
public class LocalFileStorage implements FileStorage {

    private static final Pattern KEY = Pattern.compile("[A-Za-z0-9._-]+(/[A-Za-z0-9._-]+)*");

    private final Path root;
    /** the disk keeps this much free, whatever comes: the database, the logs and the system share it */
    private final long minFreeBytes;

    public LocalFileStorage(@Value("${oro.attachments.local-dir:./data/attachments}") String directory,
                            @Value("${oro.attachments.local-min-free-bytes:1073741824}") long minFreeBytes) throws IOException {
        this.root = Path.of(directory).toAbsolutePath().normalize();
        this.minFreeBytes = minFreeBytes;
        Files.createDirectories(root);
        log.info("attachments stored in {}", root);
    }

    @Override
    public Stored put(String key, InputStream content, long maxBytes) throws IOException {
        Path target = resolve(key);
        Files.createDirectories(target.getParent());
        Path partial = Files.createTempFile(target.getParent(), ".upload-", ".part");
        try {
            MessageDigest sha256 = sha256();
            long size = 0;
            try (InputStream in = new DigestInputStream(content, sha256); OutputStream out = Files.newOutputStream(partial)) {
                byte[] buffer = new byte[64 * 1024];
                for (int read; (read = in.read(buffer)) != -1; ) {
                    size += read;
                    if (size > maxBytes) {
                        throw new TooLarge(maxBytes);
                    }
                    out.write(buffer, 0, read);
                }
            }
            Files.move(partial, target, StandardCopyOption.ATOMIC_MOVE);
            return new Stored(size, HexFormat.of().formatHex(sha256.digest()));
        } finally {
            Files.deleteIfExists(partial);
        }
    }

    @Override
    public void requireSpace(long bytes) {
        long usable;
        try {
            usable = Files.getFileStore(root).getUsableSpace();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        if (usable - bytes < minFreeBytes) {
            log.error("attachment refused: {} bytes usable on the disk of the attachments, {} kept free", usable, minFreeBytes);
            throw new ServiceUnavailable("The storage of the files is full, try again later", 600);
        }
    }

    @Override
    public InputStream open(String key) throws IOException {
        return Files.newInputStream(resolve(key));
    }

    @Override
    public void delete(String key) throws IOException {
        Files.deleteIfExists(resolve(key));
    }

    /** the path of a key, always under the root: a key is generated by Oro, checked again here */
    private Path resolve(String key) {
        if (key == null || !KEY.matcher(key).matches() || key.contains("..")) {
            throw new IllegalArgumentException("Invalid storage key");
        }
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root)) {
            throw new IllegalArgumentException("Invalid storage key");
        }
        return path;
    }

    private static MessageDigest sha256() {
        try {
            return MessageDigest.getInstance("SHA-256");
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }
}
